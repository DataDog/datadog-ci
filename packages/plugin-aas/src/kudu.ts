import type {WebSiteManagementClient} from '@azure/arm-appservice'
import type {WebApp} from '@datadog/datadog-ci-base/commands/aas/common'

import {DefaultAzureCredential} from '@azure/identity'
import {getProxyDispatcher, httpRequest, isRequestError} from '@datadog/datadog-ci-base/helpers/request'
import {thirdParty} from '@datadog/datadog-ci-base/helpers/request/third-party'

export interface KuduClient {
  deleteDirectory(directory: string, attempts?: number): Promise<void>
  publish(directory: string, archive: Buffer): Promise<void>
  hasArtifacts(artifacts: readonly (readonly string[])[]): Promise<boolean>
  /** Atomically renames `source` to `target`. Fails if `target` is a non-empty directory. */
  rename(source: string, target: string): Promise<void>
}

type PublishingCredentials = {
  properties?: {publishingPassword?: string; publishingUserName?: string; scmUri?: string}
  publishingPassword?: string
  publishingUserName?: string
  scmUri?: string
}

const RETRYABLE_SCM_STATUSES = new Set([429, 502, 503, 504])
const EXTRACTION_TIMEOUT_MS = 15 * 60_000

export const getKuduClient = async (
  client: WebSiteManagementClient,
  resourceGroup: string,
  webApp: WebApp
): Promise<KuduClient> => {
  const credentials = (await (webApp.slot
    ? client.webApps.beginListPublishingCredentialsSlotAndWait(resourceGroup, webApp.name, webApp.slot)
    : client.webApps.beginListPublishingCredentialsAndWait(resourceGroup, webApp.name))) as PublishingCredentials
  const {scmUri} = credentials.properties ?? credentials
  if (!scmUri) {
    throw new Error('SCM URL is unavailable. Enable SCM access and retry.')
  }

  const scmUrl = new URL(scmUri)
  scmUrl.username = ''
  scmUrl.password = ''
  const baseUrl = scmUrl.toString().replace(/\/$/, '')
  const azureCredential = new DefaultAzureCredential()
  const request = async <T>(
    method: string,
    path: string,
    data?: unknown,
    headers: Record<string, string> = {},
    timeout = 120_000
  ): Promise<{data: T | undefined; headers: Record<string, string>}> => {
    const token = await azureCredential.getToken('https://management.azure.com/.default')
    if (!token) {
      throw new Error('Azure credentials could not access the SCM site.')
    }
    // The SCM site answers 502/503/429 while it is still cold (for example right after an app
    // restart), so retry those with backoff instead of failing the run.
    let response
    for (let attempt = 0; ; attempt++) {
      try {
        response = await httpRequest<string>({
          method,
          url: thirdParty(`${baseUrl}${path}`),
          headers: {Authorization: `Bearer ${token.token}`, ...headers},
          data,
          dispatcher: getProxyDispatcher(),
          timeout,
        })
        break
      } catch (error) {
        const status = isRequestError(error) ? error.response?.status : undefined
        if (attempt < 5 && status !== undefined && RETRYABLE_SCM_STATUSES.has(status)) {
          await new Promise((resolve) => setTimeout(resolve, 10_000))
          continue
        }
        throw error
      }
    }

    const parsedData =
      typeof response.data === 'string'
        ? response.data
          ? (JSON.parse(response.data) as T)
          : undefined
        : (response.data as T)

    return {data: parsedData, headers: response.headers}
  }

  const runCommand = async (script: string): Promise<{ExitCode?: number; Output?: string}> => {
    const result = await request<{ExitCode?: number; Output?: string}>('POST', '/api/command', {
      command: `/bin/bash -c "${escapeBashArgument(script)}"`,
      dir: '/home',
    })

    return result.data ?? {}
  }

  return {
    publish: async (directory, archive) => {
      // Extracting a tracer onto the Azure Files-backed /home mount can take longer than the
      // ~230 s App Service front-end request limit, so a synchronous extraction request (such as
      // PUT /api/zip) loses its response. Upload the archive as a file, extract it in a detached
      // process, and poll for the exit status it writes. The VFS API creates missing parent
      // directories (/home/data does not exist until the app runtime boots, which races staging
      // on fresh apps). The command API passes backslashes through literally, so the paths (all
      // generated by the CLI) stay unquoted inside the detached script.
      const archivePath = `${directory}.zip`
      const statusPath = `${directory}.status`
      await request('PUT', `/api/vfs/${archivePath.replace(/^\/home\//, '')}`, archive, {'If-Match': '*'}, 600_000)
      const extract = `unzip -q -o ${archivePath} -d ${directory} && echo 0 > ${statusPath} || echo 1 > ${statusPath}`
      await runCommand(`setsid nohup bash -c ${shellQuote(extract)} < /dev/null > /dev/null 2>&1 &`)
      const deadline = Date.now() + EXTRACTION_TIMEOUT_MS
      for (;;) {
        await new Promise((resolve) => setTimeout(resolve, 10_000))
        const status = (await runCommand(`cat ${statusPath} 2> /dev/null`)).Output?.trim()
        if (status === '0') {
          await runCommand(`rm -f -- ${archivePath} ${statusPath}`)

          return
        }
        if (status) {
          throw new Error(`Failed to extract ${archivePath} on the Web App.`)
        }
        if (Date.now() > deadline) {
          throw new Error(
            `Extracting ${archivePath} on the Web App did not finish within ${EXTRACTION_TIMEOUT_MS / 60_000} minutes. Rerun the command to retry.`
          )
        }
      }
    },
    hasArtifacts: async (artifacts) => {
      // Parenthesize each alternative group: bash && and || are left-associative, so without
      // grouping a passing later artifact would mask a failed earlier one.
      const checks = artifacts
        .map((alternatives) => `( ${alternatives.map((artifact) => `test -f ${shellQuote(artifact)}`).join(' || ')} )`)
        .join(' && ')

      return (await runCommand(checks)).ExitCode === 0
    },
    rename: async (source, target) => {
      if ((await runCommand(`mv -T -- ${shellQuote(source)} ${shellQuote(target)}`)).ExitCode !== 0) {
        throw new Error(`Failed to move ${source} to ${target} on the Web App.`)
      }
    },
    deleteDirectory: async (directory, attempts = 7) => {
      // Deleting onto the Azure Files-backed /home mount races directory enumeration on CIFS and
      // fails while the app or sidecar still holds the files after the restart triggered by the
      // settings update, so retry with backoff long enough for the restart to settle.
      for (let attempt = 0; ; attempt++) {
        if ((await runCommand(`rm -rf -- ${directory}`)).ExitCode === 0) {
          return
        }
        if (attempt >= attempts - 1) {
          throw new Error(`Failed to delete ${directory} from the Web App.`)
        }
        await new Promise((resolve) => setTimeout(resolve, Math.min(5_000 * 2 ** attempt, 30_000)))
      }
    },
  }
}

const shellQuote = (value: string): string => `'${value.replace(/'/g, "'\\''")}'`

const escapeBashArgument = (value: string): string => value.replace(/[\\"$`]/g, '\\$&')
